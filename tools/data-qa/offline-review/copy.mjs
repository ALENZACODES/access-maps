export const COPY = Object.freeze({ en: english, fr: french });

export function message(locale, key) {
  const language = locale === 'fr' ? 'fr' : 'en';
  const value = COPY[language][key];
  if (typeof value !== 'string') throw new RangeError(`Missing bilingual key: ${key}`);
  return value;
}

export function copyKeys(locale) {
  return Object.keys(COPY[locale === 'fr' ? 'fr' : 'en']).sort();
}

export function allCopyKeysPaired() {
  const en = copyKeys('en');
  const fr = copyKeys('fr');
  return en.length === fr.length && en.every((key, index) => key === fr[index]);
}

