export function impactLocale(value) {
  return value === 'fr' ? 'fr' : 'en';
}

export function impactWords(locale) {
  return locale === 'fr' ? fr : en;
}

export function impactRule(code, locale) {
  return locale === 'fr' ? frenchRules[code] ?? code : IMPACT_RULES[code] ?? code;
}

export function impactMessageCoverage() {
  return Object.freeze({
    missingFrench: Object.keys(IMPACT_RULES).filter((key) => !Object.hasOwn(frenchRules, key)),
    missingEnglish: Object.keys(fr).filter((key) => !Object.hasOwn(en, key)),
    missingTranslations: Object.keys(en).filter((key) => !Object.hasOwn(fr, key)),
  });
}
