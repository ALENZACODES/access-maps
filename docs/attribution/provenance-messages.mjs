export function localeFor(value) {
  return typeof value === 'string' && value.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export function wordsFor(value) {
  return WORDS[localeFor(value)];
}

export function severityName(locale, severity) {
  const words = wordsFor(locale);
  return severity === 'error' ? words.errors
    : severity === 'warning' ? words.warnings : words.information;
}

export function statusName(locale, value) {
  const words = wordsFor(locale);
  return value === 'included' ? words.included
    : value === 'held' ? words.held : words.excluded;
}

export function providerName(locale, value) {
  return wordsFor(locale)[value] ?? value;
}

export function useName(locale, value) {
  return wordsFor(locale)[value === 'other' ? 'useOther' : value] ?? value;
}

