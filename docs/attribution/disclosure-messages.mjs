export function disclosureLocale(input) {
  return String(input ?? 'en').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export function disclosureWords(input) {
  return DISCLOSURE_WORDS[disclosureLocale(input)];
}

export function disclosureRule(input, code) {
  return disclosureLocale(input) === 'fr'
    ? DISCLOSURE_RULES_FR[code] ?? code
    : DISCLOSURE_RULES[code] ?? code;
}

export function disclosureSeverity(input, severity) {
  const words = disclosureWords(input);
  return severity === 'error' ? words.errors : severity === 'warning' ? words.warnings : words.infos;
}
