export function localeFromSearch(search) {
  const params = new URLSearchParams(typeof search === 'string' && search.length <= 512 ? search : '');
  return params.get('lang') === 'fr' ? 'fr' : 'en';
}
export function label(locale, key) { return COPY[locale === 'fr' ? 'fr' : 'en'][key] ?? key; }
